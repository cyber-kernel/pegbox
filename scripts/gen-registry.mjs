import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ToolManifestSchema } from '../packages/tool-kit/src/validation.ts';

const ROOT = path.resolve();
const TOOLS_DIR = path.join(ROOT, 'tools');
const OUT_FILE = path.join(ROOT, 'apps/web/src/lib/registry.generated.ts');

async function main() {
  console.log('Generating Pegbox Tool Registry...');

  if (!fs.existsSync(TOOLS_DIR)) {
    fs.mkdirSync(TOOLS_DIR, { recursive: true });
  }

  const entries = fs.readdirSync(TOOLS_DIR, { withFileTypes: true });
  const toolDirs = entries.filter((e) => e.isDirectory()).map((e) => e.name);

  const manifests = [];
  const loaders = [];
  const ids = new Set();

  for (const dirName of toolDirs) {
    const manifestPath = path.join(TOOLS_DIR, dirName, 'manifest.ts');
    if (!fs.existsSync(manifestPath)) {
      console.warn(`[SKIP] Tool folder "${dirName}" has no manifest.ts`);
      continue;
    }

    const manifestUrl = pathToFileURL(manifestPath).href;
    const mod = await import(manifestUrl);
    const rawManifest = mod.manifest;

    if (!rawManifest) {
      throw new Error(`[ERROR] ${manifestPath} does not export "manifest"`);
    }

    // Validate with Zod
    const parsed = ToolManifestSchema.safeParse(rawManifest);
    if (!parsed.success) {
      throw new Error(`[INVALID MANIFEST in ${dirName}]: ${JSON.stringify(parsed.error.format(), null, 2)}`);
    }

    const m = parsed.data;

    // Kebab case and folder name match check
    if (m.id !== dirName) {
      throw new Error(`[MISMATCH] Tool manifest id "${m.id}" does not match directory name "${dirName}"`);
    }

    // Duplicate check
    if (ids.has(m.id)) {
      throw new Error(`[DUPLICATE] Tool id "${m.id}" is defined multiple times`);
    }
    ids.add(m.id);

    // Live tool checks
    if (m.status === 'live') {
      const selftestPath = path.join(TOOLS_DIR, dirName, 'selftest.ts');
      if (!fs.existsSync(selftestPath)) {
        throw new Error(`[MISSING SELFTEST] Tool "${m.id}" is marked 'live' but missing selftest.ts`);
      }
    }

    manifests.push(m);
    loaders.push(`  '${m.id}': () => import('tools/${m.id}').then(m => m.default as ToolModule)`);
  }

  // Validate next tool IDs exist
  for (const m of manifests) {
    if (m.next && m.next.length > 0) {
      for (const nextId of m.next) {
        if (!ids.has(nextId)) {
          console.warn(`[WARN] Tool "${m.id}" references next tool "${nextId}" which is not registered yet.`);
        }
      }
    }
  }

  // Generate output file
  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const generatedCode = `// AUTO-GENERATED BY scripts/gen-registry.mjs — DO NOT EDIT DIRECTLY
import type { ToolManifest, ToolModule } from '@pegbox/tool-kit';

export const MANIFESTS: ToolManifest[] = ${JSON.stringify(manifests, null, 2)};

export const TOOL_LOADERS: Record<string, () => Promise<ToolModule>> = {
${loaders.join(',\n')}
};

export function getManifest(id: string): ToolManifest | undefined {
  return MANIFESTS.find((m) => m.id === id);
}

export function getAllManifests(): ToolManifest[] {
  return MANIFESTS.filter((m) => m.status !== 'hidden');
}

export function getLiveManifests(): ToolManifest[] {
  return MANIFESTS.filter((m) => m.status === 'live');
}

export function getManifestsByCategory(cat: string): ToolManifest[] {
  return MANIFESTS.filter((m) => m.category === cat && m.status !== 'hidden');
}

export async function loadTool(id: string): Promise<ToolModule | null> {
  const loader = TOOL_LOADERS[id];
  if (!loader) return null;
  return await loader();
}
`;

  fs.writeFileSync(OUT_FILE, generatedCode, 'utf-8');
  console.log(`Successfully generated registry at ${OUT_FILE} (${manifests.length} tools registered)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

